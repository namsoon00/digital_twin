const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { frontendDependency } = require("./frontend-toolchain.cjs");
const root = path.resolve(__dirname, "..");

function sourceFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap(entry => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? sourceFiles(file) : entry.name.endsWith(".mjs") ? [file] : [];
  });
}

async function buildFrontend({ check = false } = {}) {
  const modules = sourceFiles(path.join(root, "public/modules"));
  const hash = crypto.createHash("sha256");
  // The pinned compiler and its recipe are part of the release identity too.
  hash.update("scripts/build-frontend.cjs\0").update(fs.readFileSync(__filename));
  modules.forEach(file => hash.update(path.relative(root, file)).update("\0").update(fs.readFileSync(file)));
  for (const name of ["app-default-settings.js", "console-workspaces.js", "console-workspaces.css", "styles.css", "web-runtime.js", "service-worker.js", "index.html", "_headers"]) {
    const content = fs.readFileSync(path.join(root, "public", name), "utf8")
      .replace(/(app\.js|app-default-settings\.js|console-workspaces\.js|console-workspaces\.css|styles\.css|web-runtime\.js)\?v=[^"']+/g, "$1?v=RELEASE")
      .replace(/orbit-alpha-shell-[^"']+/, "orbit-alpha-shell-RELEASE");
    hash.update(name).update("\0").update(content);
  }
  const version = "modules-" + hash.digest("hex").slice(0, 16);
  const esbuild = frontendDependency("esbuild");
  if (esbuild.version !== "0.25.10") throw new Error("Deterministic builds require esbuild 0.25.10.");
  const result = await esbuild.build({
    absWorkingDir: root, entryPoints: ["public/modules/bootstrap.mjs"], bundle: true,
    write: false, format: "iife", target: "es2020", charset: "utf8", treeShaking: false,
    legalComments: "none", metafile: true,
    define: { __FRONTEND_ASSET_VERSION__: JSON.stringify(version) },
    banner: { js: "// Generated by scripts/build-frontend.cjs. Edit public/modules/, not this file.\n// Frontend release: " + version }
  });
  const outputs = new Map([["public/app.js", result.outputFiles[0].text]]);
  const assets = ["app.js", "app-default-settings.js", "web-runtime.js", "console-workspaces.js", "styles.css", "console-workspaces.css"];
  for (const name of ["public/index.html", "public/service-worker.js"]) {
    let content = fs.readFileSync(path.join(root, name), "utf8");
    for (const asset of assets) content = content.replace(new RegExp(asset.replaceAll(".", "\\.") + "\\?v=[^\"']+", "g"), asset + "?v=" + version);
    content = content.replace(/orbit-alpha-shell-[^"']+/, "orbit-alpha-shell-" + version);
    outputs.set(name, content);
  }
  for (const [name, content] of outputs) {
    if (check) {
      if (fs.readFileSync(path.join(root, name), "utf8") !== content) throw new Error(name + " is stale; run node scripts/build-frontend.cjs");
    } else fs.writeFileSync(path.join(root, name), content);
  }
  return { version, modules: modules.length, bytes: Buffer.byteLength(result.outputFiles[0].text) };
}

if (require.main === module) buildFrontend({ check: process.argv.includes("--check") }).then(result => console.log(result)).catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { buildFrontend, sourceFiles };
